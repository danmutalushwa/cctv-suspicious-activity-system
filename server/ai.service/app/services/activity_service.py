import numpy as np
from typing import List, Dict, Any, Optional

from app.config import config
from app.utils.logger import logger


class ActivityService:
    """
    Service responsible for identifying suspicious
    activities from tracked people.
    """

    def __init__(self):
        self.suspicious_behaviors = {}
        self.intrusion_zones = []

        self.initialize_zones()

        logger.info(
            "Activity service initialized with "
            f"{len(self.intrusion_zones)} intrusion zone(s)"
        )

    # =========================================================
    # INTRUSION ZONES
    # =========================================================

    def initialize_zones(self):
        """
        Define monitored/restricted areas.

        The coordinates are designed for the 640x360
        frames currently generated by the Node backend.

        You can later make these configurable per camera.
        """

        self.intrusion_zones = [
            {
                'id': 'zone_1',
                'name': 'Restricted Area',
                'polygon': [
                    (80, 60),
                    (560, 60),
                    (560, 330),
                    (80, 330)
                ],
                'level': 'high'
            }
        ]

    # =========================================================
    # INTRUSION
    # =========================================================

    def detect_intrusion(
        self,
        track: Dict[str, Any]
    ) -> Dict[str, Any]:

        centroid = track.get('centroid')

        if not centroid:
            return {
                'intrusion': False
            }

        for zone in self.intrusion_zones:

            if self.point_in_polygon(
                centroid,
                zone['polygon']
            ):
                return {
                    'intrusion': True,
                    'zone': zone['name'],
                    'zone_id': zone['id'],
                    'severity': zone['level']
                }

        return {
            'intrusion': False
        }

    # =========================================================
    # POINT IN POLYGON
    # =========================================================

    def point_in_polygon(
        self,
        point: List[int],
        polygon: List[tuple]
    ) -> bool:

        x, y = point

        n = len(polygon)

        inside = False

        p1x, p1y = polygon[0]

        for i in range(1, n + 1):

            p2x, p2y = polygon[i % n]

            if y > min(p1y, p2y):

                if y <= max(p1y, p2y):

                    if x <= max(p1x, p2x):

                        if p1y != p2y:

                            xinters = (
                                (y - p1y)
                                * (p2x - p1x)
                                / (p2y - p1y)
                                + p1x
                            )

                        if (
                            p1x == p2x
                            or x <= xinters
                        ):
                            inside = not inside

            p1x, p1y = p2x, p2y

        return inside

    # =========================================================
    # RAPID MOVEMENT
    # =========================================================

    def detect_rapid_movement(
        self,
        track: Dict[str, Any],
        threshold: Optional[float] = None
    ) -> bool:

        if threshold is None:
            threshold = config.RAPID_MOVEMENT_THRESHOLD

        positions = track.get(
            'positions',
            []
        )

        if len(positions) < 5:
            return False

        recent_positions = positions[-5:]

        speeds = []

        for i in range(
            1,
            len(recent_positions)
        ):

            dx = (
                recent_positions[i][0]
                - recent_positions[i - 1][0]
            )

            dy = (
                recent_positions[i][1]
                - recent_positions[i - 1][1]
            )

            speed = np.sqrt(
                dx ** 2 + dy ** 2
            )

            speeds.append(speed)

        avg_speed = (
            float(np.mean(speeds))
            if speeds
            else 0
        )

        return avg_speed > threshold

    # =========================================================
    # LOITERING
    # =========================================================

    def detect_loitering(
        self,
        track: Dict[str, Any]
    ) -> bool:

        positions = track.get(
            'positions',
            []
        )

        required_frames = config.LOITERING_TIME

        if len(positions) < required_frames:
            return False

        recent_positions = positions[
            -required_frames:
        ]

        if len(recent_positions) < 2:
            return False

        movements = []

        for i in range(
            1,
            len(recent_positions)
        ):

            dx = (
                recent_positions[i][0]
                - recent_positions[i - 1][0]
            )

            dy = (
                recent_positions[i][1]
                - recent_positions[i - 1][1]
            )

            movement = np.sqrt(
                dx ** 2 + dy ** 2
            )

            movements.append(
                movement
            )

        avg_movement = (
            float(np.mean(movements))
            if movements
            else 0
        )

        # Person remains in approximately the
        # same area for many processed frames.
        return avg_movement < 10

    # =========================================================
    # UNUSUAL BEHAVIOR
    # =========================================================

    def detect_unusual_behavior(
        self,
        track: Dict[str, Any]
    ) -> bool:

        time_visible = track.get(
            'time_visible',
            0
        )

        positions = track.get(
            'positions',
            []
        )

        # Require a reasonable tracking history.
        if len(positions) < 10:
            return False

        # Long presence with very little movement.
        if (
            time_visible > 30
            and not track.get(
                'is_loitering',
                False
            )
        ):

            return True

        return False

    # =========================================================
    # MAIN ACTIVITY ANALYSIS
    # =========================================================

    def analyze_activity(
        self,
        track: Dict[str, Any]
    ) -> Dict[str, Any]:

        analysis = {
            'track_id': track.get(
                'track_id'
            ),

            'is_suspicious': False,

            'activities': [],

            'severity': 'low',

            'reasons': []
        }

        # -----------------------------------------------------
        # LOITERING
        # -----------------------------------------------------

        is_loitering = (
            self.detect_loitering(track)
        )

        if is_loitering:

            analysis['activities'].append(
                'loitering'
            )

            analysis['reasons'].append(
                'Person remained in the same area '
                'for an extended period'
            )

            analysis['is_suspicious'] = True

            analysis['severity'] = 'medium'

        # -----------------------------------------------------
        # INTRUSION
        # -----------------------------------------------------

        intrusion = (
            self.detect_intrusion(track)
        )

        if intrusion.get('intrusion'):

            analysis['activities'].append(
                'intrusion'
            )

            analysis['reasons'].append(
                f"Person entered restricted zone "
                f"'{intrusion.get('zone')}'"
            )

            analysis['is_suspicious'] = True

            analysis['severity'] = 'high'

            analysis['zone'] = (
                intrusion.get('zone')
            )

            analysis['zone_id'] = (
                intrusion.get('zone_id')
            )

        # -----------------------------------------------------
        # RAPID MOVEMENT
        # -----------------------------------------------------

        if self.detect_rapid_movement(track):

            analysis['activities'].append(
                'rapid_movement'
            )

            analysis['reasons'].append(
                'Rapid movement detected'
            )

            analysis['is_suspicious'] = True

            if analysis['severity'] == 'low':
                analysis['severity'] = 'high'

        # -----------------------------------------------------
        # UNUSUAL BEHAVIOR
        # -----------------------------------------------------

        if self.detect_unusual_behavior(track):

            analysis['activities'].append(
                'unusual_behavior'
            )

            analysis['reasons'].append(
                'Unusual prolonged behavior pattern detected'
            )

            analysis['is_suspicious'] = True

            if analysis['severity'] == 'low':
                analysis['severity'] = 'medium'

        # -----------------------------------------------------
        # FINAL REASON
        # -----------------------------------------------------

        if analysis['reasons']:

            analysis['reason'] = '; '.join(
                analysis['reasons']
            )

        else:

            analysis['reason'] = (
                'No suspicious behavior detected'
            )

        return analysis


activity_service = ActivityService()